"""Dinosaur silhouettes drawn from code.

Each animal is a hand-placed body outline (tail, torso, neck and head in one closed shape)
smoothed with Chaikin corner cutting, plus limbs drawn as tapered strokes in a walking pose
and ornaments (plates, horns, sails). Shapes face right and stand on y=0.
`silhouette(kind)` returns a list of polygons (Nx2 arrays) filled with one colour.
"""
from __future__ import annotations

import numpy as np


def blob(points, iterations: int = 3) -> np.ndarray:
    """Closed outline with its corners cut (Chaikin), so it reads as soft tissue."""
    p = np.asarray(points, dtype=float)
    for _ in range(iterations):
        nxt = np.roll(p, -1, axis=0)
        p = np.column_stack([0.75 * p + 0.25 * nxt, 0.25 * p + 0.75 * nxt]).reshape(-1, 2)
    return p


def stroke(points, widths, samples: int = 40) -> np.ndarray:
    """Polygon around a Catmull-Rom curve through `points`, thickness interpolated from `widths`."""
    pts = np.asarray(points, dtype=float)
    padded = np.vstack([2 * pts[0] - pts[1], pts, 2 * pts[-1] - pts[-2]])
    curve = []
    per = max(4, samples // (len(pts) - 1))
    for i in range(len(pts) - 1):
        p0, p1, p2, p3 = padded[i : i + 4]
        for t in np.linspace(0, 1, per, endpoint=False):
            curve.append(0.5 * (2 * p1 + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t**2 + (-p0 + 3 * p1 - 3 * p2 + p3) * t**3))
    curve.append(pts[-1])
    curve = np.array(curve)
    seg = np.linalg.norm(np.diff(pts, axis=0), axis=1)
    knots = np.concatenate([[0], np.cumsum(seg)]) / max(seg.sum(), 1e-9)
    along = np.concatenate([[0], np.cumsum(np.linalg.norm(np.diff(curve, axis=0), axis=1))])
    half = np.interp(along / max(along[-1], 1e-9), knots, widths) / 2
    tangent = np.gradient(curve, axis=0)
    tangent /= np.maximum(np.linalg.norm(tangent, axis=1, keepdims=True), 1e-9)
    normal = np.column_stack([-tangent[:, 1], tangent[:, 0]])
    return np.vstack([curve + normal * half[:, None], (curve - normal * half[:, None])[::-1]])


def ellipse(cx: float, cy: float, rx: float, ry: float, angle: float = 0.0) -> np.ndarray:
    t = np.linspace(0, 2 * np.pi, 48)
    x, y = rx * np.cos(t), ry * np.sin(t)
    c, s = np.cos(angle), np.sin(angle)
    return np.column_stack([cx + c * x - s * y, cy + s * x + c * y])


def hind_leg(hx: float, hy: float, w: float, stride: float, sickle: bool = False) -> list[np.ndarray]:
    """Digitigrade biped leg: muscular thigh, forward knee, backward ankle, three-toed foot.

    stride > 0 swings the leg forward, < 0 back (near and far legs of a walking pose).
    """
    h = hy
    knee = (hx + (0.12 + 0.12 * stride) * h, hy - 0.4 * h)
    ankle = (hx + (0.0 + 0.2 * stride) * h, hy - 0.72 * h)
    ball = (hx + (0.1 + 0.24 * stride) * h, 0.035)
    toe = (hx + (0.28 + 0.24 * stride) * h, 0.0)
    parts = [
        ellipse(hx + 0.05 * h + 0.06 * stride * h, hy - 0.2 * h, 0.78 * w, 1.45 * w, 0.4 + 0.3 * stride),
        stroke([(hx, hy), knee, ankle, ball], [1.2 * w, 0.6 * w, 0.4 * w, 0.32 * w]),
        stroke([ball, ((ball[0] + toe[0]) / 2, 0.022), toe], [0.34 * w, 0.22 * w, 0.04 * w]),
        stroke([ball, (ball[0] - 0.07 * h, 0.012)], [0.26 * w, 0.03]),
    ]
    if sickle:
        parts.append(stroke([(ball[0] + 0.02 * h, 0.05), (ball[0] + 0.06 * h, 0.12), (ball[0] + 0.11 * h, 0.1)], [0.14 * w, 0.08 * w, 0.0]))
    return parts


def pillar(x: float, top: float, w: float, lean: float = 0.0) -> list[np.ndarray]:
    """Columnar quadruped leg with a fleshy upper limb and a padded foot."""
    return [
        ellipse(x, top - 0.12, 0.62 * w, 0.95 * w),
        stroke([(x, top), (x - 0.03 + lean * 0.5, top * 0.5), (x + lean, 0.07)], [w, 0.72 * w, 0.7 * w]),
        ellipse(x + lean + 0.05 * w, 0.055, 0.62 * w, 0.055),
    ]


def arm(points, w: float, claws: int = 1) -> list[np.ndarray]:
    parts = [stroke(points, [w, 0.7 * w, 0.4 * w][: len(points)] + [0.4 * w] * max(0, len(points) - 3))]
    x, y = points[-1]
    for i in range(claws):
        parts.append(stroke([(x, y), (x + 0.05, y - 0.03 - 0.02 * i), (x + 0.06, y - 0.08 - 0.02 * i)], [0.25 * w, 0.12 * w, 0.0]))
    return parts


